// ─── Derive the CLI's installable registries from the docs-site registries ───
//
// The docs site (app/_docs/registry/index.ts and blocks.ts) is the single
// source of truth for component/block metadata. The CLI only needs a strict
// subset of that data (name, slug, files, npm deps, registryDependencies) to
// resolve `npx dafink-ui add <slug>`, so packages/cli/src/lib/registry.ts and
// blocksRegistry.ts are generated here instead of hand-maintained. Hand-editing
// them used to drift silently from the docs registries — see the "Dual
// component/block registries" footgun in AGENTS.md.

/** Transpiles a pure-data .ts file (no JSX, no non-builtin imports) to plain
 * JS and dynamically imports it, so its exported arrays can be read at build
 * time without a full TypeScript program. */
async function importDataModule(tsSourcePath)
{
	const source = readFileSync(tsSourcePath, 'utf8');
	const { outputText } = ts.transpileModule(source, {
		compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 },
	});

	const tempPath = tsSourcePath.replace(/\.ts$/, `.generated-tmp-${process.pid}-${Date.now()}.mjs`);
	writeFileSync(tempPath, outputText);

	try
	{
		return await import(pathToFileURL(tempPath).href);
	}
	finally
	{
		unlinkSync(tempPath);
	}
}

const quoteString = (value) => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const quoteArray  = (values) => `[${values.map(quoteString).join(', ')}]`;

function renderRegistryFile({ header, interfaceBlock, entries, arrayName, helperBlock })
{
	const entryLines = entries.map(({ name, slug, files, deps, registryDependencies }) =>
		`\t{ name: ${quoteString(name)}, slug: ${quoteString(slug)}, files: ${quoteArray(files)}, deps: ${quoteArray(deps)}, registryDependencies: ${quoteArray(registryDependencies)} },`
	).join('\n');

	return `${header}\n\n${interfaceBlock}\n\nexport const ${arrayName} = [\n${entryLines}\n];\n\n${helperBlock}\n`;
}

const GENERATED_HEADER = [
	'// AUTO-GENERATED by packages/cli/scripts/build-registry.mjs — do not edit by hand.',
	'// Source of truth: app/_docs/registry/ (index.ts for components, blocks.ts for blocks).',
	'// Run `npm run sync-registry` from the repo root to regenerate this file.',
].join('\n');

const { registry: docsComponents } = await importDataModule(docsComponentRegistryPath);
const { blocks: docsBlocks } = await importDataModule(docsBlockRegistryPath);

const cliComponentEntries = docsComponents.map(({ name, slug, files, dependencies, registryDependencies }) =>
	({ name, slug, files, deps: dependencies, registryDependencies })
);

const cliBlockEntries = docsBlocks.map(({ name, slug, files, dependencies, registryDependencies }) =>
	({ name, slug, files, deps: dependencies, registryDependencies })
);

writeFileSync(cliComponentRegistryPath, renderRegistryFile({
	header: GENERATED_HEADER,
	interfaceBlock: [
		'export interface RegistryEntry',
		'{',
		'\tname: string;',
		'\tslug: string;',
		'\tfiles: string[];',
		'\tdeps: string[];',
		'\tregistryDependencies: string[];',
		'}',
	].join('\n'),
	entries: cliComponentEntries,
	arrayName: 'REGISTRY: RegistryEntry[]',
	helperBlock: [
		'export function findBySlug(slug: string): RegistryEntry | undefined',
		'{',
		'\treturn REGISTRY.find(e => e.slug === slug);',
		'}',
		'',
		'export function findByName(name: string): RegistryEntry | undefined',
		'{',
		'\treturn REGISTRY.find(e => e.name.toLowerCase() === name.toLowerCase());',
		'}',
		'',
		'export function resolve(input: string): RegistryEntry | undefined',
		'{',
		'\treturn findBySlug(input) ?? findByName(input);',
		'}',
	].join('\n'),
}));
console.log(`\nCLI component registry generated: ${cliComponentEntries.length} entries → ${cliComponentRegistryPath}`);

writeFileSync(cliBlockRegistryPath, renderRegistryFile({
	header: GENERATED_HEADER,
	interfaceBlock: [
		'export interface BlockRegistryEntry',
		'{',
		'\tname: string;',
		'\tslug: string;',
		'\tfiles: string[];',
		'\tdeps: string[];',
		'\tregistryDependencies: string[];',
		'}',
	].join('\n'),
	entries: cliBlockEntries,
	arrayName: 'BLOCKS_REGISTRY: BlockRegistryEntry[]',
	helperBlock: [
		'export function findBlockBySlug(slug: string): BlockRegistryEntry | undefined',
		'{',
		'\treturn BLOCKS_REGISTRY.find(e => e.slug === slug);',
		'}',
		'',
		'export function findBlockByName(name: string): BlockRegistryEntry | undefined',
		'{',
		'\treturn BLOCKS_REGISTRY.find(e => e.name.toLowerCase() === name.toLowerCase());',
		'}',
		'',
		'export function resolveBlock(input: string): BlockRegistryEntry | undefined',
		'{',
		'\treturn findBlockBySlug(input) ?? findBlockByName(input);',
		'}',
	].join('\n'),
}));
console.log(`Block CLI registry generated: ${cliBlockEntries.length} entries → ${cliBlockRegistryPath}`);
